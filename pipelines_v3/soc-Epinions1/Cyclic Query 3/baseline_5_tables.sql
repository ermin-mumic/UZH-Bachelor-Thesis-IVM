-- Cyclic Query 3.
CREATE MATERIALIZED VIEW BASELINE_QUERY AS
SELECT R1.A AS A, R2.B AS B, R3.C AS C, R4.D AS D
FROM R1
JOIN R2 ON R1.B = R2.B
JOIN R3 ON R2.C = R3.C
JOIN R4 ON R4.D = R3.D AND R4.B = R2.B AND (R4.B = R1.B)
JOIN R5 ON R5.A = R1.A AND R5.D = R4.D AND (R5.D =R3.D);
